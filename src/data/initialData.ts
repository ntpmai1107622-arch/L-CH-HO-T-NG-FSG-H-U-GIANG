export function normalizeStatus(status?: ActivityStatus | string): 'loading' | 'done' | 'cancel' {
  if (!status) return 'loading';
  const s = status.toLowerCase();
  if (s === 'done' || s === 'completed') return 'done';
  if (s === 'cancel' || s === 'cancelled') return 'cancel';
  return 'loading'; // loading, planned, in_progress
}

